# Embed the player's data as C arrays (what introasm.asm did with incbin).
# (Script and V2MEnd are declared by mainplayer.cpp but not used.)
import sys
src, out = sys.argv[1], sys.argv[2]
def arr(name, path, end=None):
    b = open(path, 'rb').read()
    body = ','.join(str(x) for x in b)
    s = f'extern "C" __attribute__((aligned(16))) unsigned char {name}[{len(b) + 1}] = {{{body},0}};\n'
    if end: s += f'extern "C" unsigned char *const {end}_ptr = {name} + {len(b)};\n'
    return s
with open(out, 'w') as o:
    o.write('// generated by web/mkdata.py from genthree/data\n')
    o.write(arr('BabeMesh', src + '/babe.mesh'))
    o.write(arr('V2MTune', src + '/josie_v2new.v2m'))   # converted by web/tools/convv2m.cpp
    o.write(arr('ScriptPack', src + '/candytron_final_064.pac'))
